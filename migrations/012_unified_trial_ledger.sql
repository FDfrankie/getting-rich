PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS unified_trials (
    trial_id TEXT PRIMARY KEY,
    domain TEXT NOT NULL CHECK (domain IN ('WORLDQUANT_ALPHA', 'CRYPTO_MODEL', 'CRYPTO_STRATEGY', 'CRYPTO_EXECUTION', 'SYSTEM_VALIDATION')),
    stage TEXT NOT NULL CHECK (stage IN ('CREATED', 'DATA_VALIDATION', 'TRAINING', 'LOCAL_EVALUATION', 'OFFICIAL_EVALUATION', 'ROBUSTNESS', 'SHADOW', 'TESTNET', 'CANARY', 'PRODUCTION', 'COMPLETED', 'FAILED', 'BLOCKED', 'INVALIDATED', 'ARCHIVED')),
    result_status TEXT NOT NULL DEFAULT 'PENDING' CHECK (result_status IN ('PENDING', 'PASS', 'FAIL', 'UNVERIFIED', 'ERROR', 'CANCELLED')),
    parent_trial_id TEXT,
    root_trial_id TEXT,
    hypothesis_id TEXT,
    artifact_id TEXT,
    candidate_id TEXT,
    policy_version TEXT NOT NULL,
    generator_version TEXT,
    evaluator_version TEXT NOT NULL DEFAULT 'v1',
    schema_version TEXT NOT NULL DEFAULT 'trial-ledger-v1',
    code_commit_sha TEXT NOT NULL,
    config_hash TEXT NOT NULL,
    data_snapshot_hash TEXT NOT NULL,
    feature_snapshot_hash TEXT,
    input_snapshot_hash TEXT NOT NULL,
    result_snapshot_hash TEXT,
    random_seed INTEGER,
    train_start TEXT,
    train_end TEXT,
    validation_start TEXT,
    validation_end TEXT,
    test_start TEXT,
    test_end TEXT,
    test_revealed_at TEXT,
    modified_after_test INTEGER NOT NULL DEFAULT 0 CHECK (modified_after_test IN (0, 1)),
    evidence_level TEXT NOT NULL DEFAULT 'UNKNOWN' CHECK (evidence_level IN ('OFFICIAL', 'TESTNET', 'RECORDED_FIXTURE', 'LOCAL_REPLICATION', 'INFERRED_PROXY', 'UNKNOWN')),
    official_reference_id TEXT,
    external_job_id TEXT,
    objective_vector_json TEXT NOT NULL DEFAULT '{}',
    metrics_json TEXT NOT NULL DEFAULT '{}',
    failure_gates_json TEXT NOT NULL DEFAULT '[]',
    warnings_json TEXT NOT NULL DEFAULT '[]',
    simulation_minutes REAL CHECK (simulation_minutes IS NULL OR simulation_minutes >= 0),
    created_at TEXT NOT NULL,
    started_at TEXT,
    completed_at TEXT,
    invalidated_at TEXT,
    invalidation_reason TEXT,
    FOREIGN KEY (parent_trial_id) REFERENCES unified_trials(trial_id),
    FOREIGN KEY (root_trial_id) REFERENCES unified_trials(trial_id),
    CHECK (modified_after_test = 0 OR test_revealed_at IS NOT NULL),
    UNIQUE (domain, input_snapshot_hash, policy_version, evaluator_version)
);

CREATE INDEX IF NOT EXISTS idx_trials_domain_stage ON unified_trials (domain, stage, result_status, created_at);
CREATE INDEX IF NOT EXISTS idx_trials_lineage ON unified_trials (root_trial_id, parent_trial_id, created_at);

CREATE TABLE IF NOT EXISTS alpha_trial_details (
    trial_id TEXT PRIMARY KEY,
    region TEXT NOT NULL,
    universe TEXT NOT NULL,
    delay INTEGER NOT NULL CHECK (delay IN (0, 1)),
    dataset_id TEXT,
    dataset_category TEXT NOT NULL,
    blueprint_family TEXT NOT NULL,
    raw_expression TEXT NOT NULL,
    canonical_expression TEXT NOT NULL,
    exact_hash TEXT NOT NULL,
    normalized_hash TEXT NOT NULL,
    structural_hash TEXT NOT NULL,
    settings_json TEXT NOT NULL,
    official_simulation_id TEXT,
    brain_alpha_id TEXT,
    sharpe REAL,
    fitness REAL,
    returns REAL,
    turnover REAL,
    margin REAL,
    drawdown REAL,
    self_correlation REAL CHECK (self_correlation IS NULL OR (self_correlation >= -1 AND self_correlation <= 1)),
    prod_correlation REAL CHECK (prod_correlation IS NULL OR (prod_correlation >= -1 AND prod_correlation <= 1)),
    sub_universe_sharpe REAL,
    sub_universe_cutoff REAL,
    weight_test_passed INTEGER,
    bias_test_passed INTEGER,
    sub_universe_passed INTEGER,
    FOREIGN KEY (trial_id) REFERENCES unified_trials(trial_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS crypto_trial_details (
    trial_id TEXT PRIMARY KEY,
    exchange TEXT NOT NULL,
    market_type TEXT NOT NULL CHECK (market_type IN ('SPOT', 'USD_M_FUTURES', 'COIN_M_FUTURES')),
    symbol TEXT NOT NULL,
    timeframe TEXT NOT NULL,
    strategy_name TEXT NOT NULL,
    model_name TEXT,
    position_mode TEXT CHECK (position_mode IS NULL OR position_mode IN ('ONE_WAY', 'HEDGE')),
    margin_mode TEXT CHECK (margin_mode IS NULL OR margin_mode IN ('ISOLATED', 'CROSS')),
    requested_leverage REAL CHECK (requested_leverage IS NULL OR requested_leverage > 0),
    effective_leverage REAL CHECK (effective_leverage IS NULL OR effective_leverage > 0),
    equity REAL CHECK (equity IS NULL OR equity >= 0),
    gross_return REAL,
    net_return REAL,
    sharpe REAL,
    deflated_sharpe_probability REAL CHECK (deflated_sharpe_probability IS NULL OR (deflated_sharpe_probability >= 0 AND deflated_sharpe_probability <= 1)),
    pbo REAL CHECK (pbo IS NULL OR (pbo >= 0 AND pbo <= 1)),
    max_drawdown REAL,
    turnover REAL,
    fee_cost REAL,
    spread_cost REAL,
    slippage_cost REAL,
    funding_cost REAL,
    unknown_order_count INTEGER CHECK (unknown_order_count IS NULL OR unknown_order_count >= 0),
    reconciliation_failure_count INTEGER CHECK (reconciliation_failure_count IS NULL OR reconciliation_failure_count >= 0),
    risk_violation_count INTEGER CHECK (risk_violation_count IS NULL OR risk_violation_count >= 0),
    FOREIGN KEY (trial_id) REFERENCES unified_trials(trial_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS unified_trial_events (
    event_id TEXT PRIMARY KEY,
    trial_id TEXT NOT NULL,
    event_type TEXT NOT NULL,
    event_version INTEGER NOT NULL DEFAULT 1,
    idempotency_key TEXT NOT NULL,
    payload_json TEXT NOT NULL DEFAULT '{}',
    evidence_level TEXT NOT NULL,
    created_at TEXT NOT NULL,
    FOREIGN KEY (trial_id) REFERENCES unified_trials(trial_id) ON DELETE CASCADE,
    UNIQUE (trial_id, idempotency_key)
);

CREATE TABLE IF NOT EXISTS trial_test_access_log (
    access_id TEXT PRIMARY KEY,
    trial_id TEXT NOT NULL,
    test_period_revealed INTEGER NOT NULL CHECK (test_period_revealed IN (0, 1)),
    result_consumed_by_generator INTEGER NOT NULL CHECK (result_consumed_by_generator IN (0, 1)),
    consumer_name TEXT NOT NULL,
    purpose TEXT NOT NULL,
    accessed_at TEXT NOT NULL,
    FOREIGN KEY (trial_id) REFERENCES unified_trials(trial_id) ON DELETE CASCADE
);
